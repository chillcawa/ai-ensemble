const dictionaries: Record<ResolvedLocale, Record<string, string>> = { ja: {}, en, "zh-CN": zhCN, ko };

function interpolate(template: string, values?: Record<string, string | number>): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) => values[key] === undefined ? match : String(values[key]));
}

function detectLocale(): ResolvedLocale {
  const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const language of languages) {
    const normalized = language.toLowerCase();
    if (normalized.startsWith("ja")) return "ja";
    if (normalized.startsWith("ko")) return "ko";
    if (normalized === "zh-cn" || normalized === "zh-sg" || normalized.startsWith("zh-hans")) return "zh-CN";
  }
  return "en";
}

interface I18nValue {
  locale: AppLocale;
  resolvedLocale: ResolvedLocale;
  setLocale: (locale: AppLocale) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<AppLocale>(() => readStorage<AppLocale>(STORAGE_KEY, "system"));
  const resolvedLocale = locale === "system" ? detectLocale() : locale;

  const setLocale = (next: AppLocale) => {
    setLocaleState(next);
    writeStorage(STORAGE_KEY, next);
  };

  useEffect(() => {
    document.documentElement.lang = resolvedLocale;
  }, [resolvedLocale]);

  const value = useMemo<I18nValue>(() => ({
    locale,
    resolvedLocale,
    setLocale,
    // Japanese source strings are the canonical copy. They must not fall
    // through to the English dictionary when Japanese is selected.
    t: (key, values) => interpolate(
      resolvedLocale === "ja" ? key : dictionaries[resolvedLocale][key] ?? en[key] ?? key,
      values,
    ),
  }), [locale, resolvedLocale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

export const LANGUAGE_STORAGE_KEY = STORAGE_KEY;
